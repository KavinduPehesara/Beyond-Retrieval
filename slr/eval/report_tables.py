"""Turn run directories into the tables that go into the final report.

Reads every ``runs/*/metrics.json`` and writes:

    reports/results.csv   one row per (run, review) — for analysis
    reports/results.md    one table per review, prevalence in the heading

Nothing here computes a new number. Every cell is copied from a metrics file,
so every figure in the report traces to a run directory (rule 2). Results are
grouped per review and never pooled (rule 5).

Usage:
    python -m slr.eval.report_tables --runs runs --out reports
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

from slr.eval.harness import METRICS_SCHEMA

COLUMNS = [
    "review",
    "n_records",
    "prevalence",
    "run",
    "config",
    "mode",
    "strategy",
    "model",
    "prompt_version",
    "criteria_status",
    "aborted",
    "n_screened",
    "verification_rate",
    "recall_verified",
    "recall_with_referrals",
    "precision_verified",
    "work_saved",
    "agreement_ac1",
    "agreement_pabak",
    "recall_target",
    "ranking_complete",
    "tnr_at_recall",
    "wss_at_recall",
    "cost_usd_at_config_prices",
]


def load_runs(runs_dir: Path) -> list[tuple[str, dict]]:
    """(run directory name, metrics) for every readable run, oldest first."""
    runs = []
    for path in sorted(Path(runs_dir).glob("*/metrics.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("metrics_schema") != METRICS_SCHEMA:
            print(
                f"skipping {path.parent.name}: metrics schema "
                f"{data.get('metrics_schema')!r}, expected {METRICS_SCHEMA}",
                file=sys.stderr,
            )
            continue
        runs.append((path.parent.name, data))
    return runs


def rows_for(run_name: str, data: dict) -> list[dict]:
    screening = data.get("screening") or {}
    rows = []
    for m in data["per_review"]:
        ranking = m.get("ranking") or {}
        rows.append(
            {
                "review": m["review"],
                "n_records": m["n_records"],
                "prevalence": m["prevalence"],
                "run": run_name,
                "config": data["config_name"],
                "mode": data["mode"],
                "strategy": data["ranking"]["strategy"],
                "model": screening.get("model"),
                "prompt_version": screening.get("prompt_version"),
                "criteria_status": data["criteria"][m["review"]]["status"],
                "aborted": data["aborted"],
                "n_screened": m.get("n_screened"),
                "verification_rate": m.get("verification_rate"),
                "recall_verified": m.get("recall_verified"),
                "recall_with_referrals": m.get("recall_with_referrals"),
                "precision_verified": m.get("precision_verified"),
                "work_saved": m.get("work_saved"),
                "agreement_ac1": m.get("agreement_ac1"),
                "agreement_pabak": m.get("agreement_pabak"),
                "recall_target": ranking.get("recall_target"),
                "ranking_complete": ranking.get("complete"),
                "tnr_at_recall": ranking.get("tnr_at_recall"),
                "wss_at_recall": ranking.get("wss_at_recall"),
                "cost_usd_at_config_prices": m.get("cost_usd_at_config_prices"),
            }
        )
    return rows


def _cell(value, spec: str = ".3f") -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return format(value, spec)
    return str(value)


def to_markdown(rows: list[dict]) -> str:
    """One table per review, lowest prevalence first."""
    if not rows:
        return "No runs found.\n"

    by_review: dict[str, list[dict]] = {}
    for row in rows:
        by_review.setdefault(row["review"], []).append(row)

    out = [
        "# Results",
        "",
        "Generated by `python -m slr.eval.report_tables` from run directories.",
        "Every cell is copied from a `metrics.json`. Reviews are never pooled.",
        "",
        "Legend: *Rec (v)* recall over verified decisions; *Rec (+h)* recall once",
        "referrals to a human are counted; *Saved* records excluded without a",
        "human; *TNR@r* true negative rate at the recall target (normalised WSS).",
        "`†` ranking covers only the screened records; `‡` draft eligibility",
        "criteria — not reportable.",
        "",
    ]
    for review, group in sorted(by_review.items(), key=lambda kv: (kv[1][0]["prevalence"], kv[0])):
        first = group[0]
        out.append(
            f"## {review} — {first['n_records']:,} records, "
            f"{first['prevalence']:.1%} included"
        )
        out.append("")
        out.append(
            "| Run | Mode | Strategy | Model | N screened | Verified | Rec (v) | "
            "Rec (+h) | Saved | AC1 | PABAK | TNR@r | WSS@r | Cost (USD) |"
        )
        out.append("|" + "---|" * 14)
        for r in group:
            uses_criteria = r["mode"] == "screen" or r["strategy"] == "bm25"
            marks = ("†" if r["ranking_complete"] is False else "") + (
                "‡" if r["criteria_status"] != "published" and uses_criteria else ""
            )
            name = f"{r['config']}{marks}{' (aborted)' if r['aborted'] else ''}"
            out.append(
                "| "
                + " | ".join(
                    [
                        f"{name}<br>`{r['run']}`",
                        r["mode"],
                        r["strategy"],
                        _cell(r["model"]),
                        _cell(r["n_screened"]),
                        _cell(r["verification_rate"], ".1%"),
                        _cell(r["recall_verified"]),
                        _cell(r["recall_with_referrals"]),
                        _cell(r["work_saved"], ".1%"),
                        _cell(r["agreement_ac1"]),
                        _cell(r["agreement_pabak"]),
                        _cell(r["tnr_at_recall"]),
                        _cell(r["wss_at_recall"]),
                        _cell(r["cost_usd_at_config_prices"], ".4f"),
                    ]
                )
                + " |"
            )
        out.append("")
    return "\n".join(out)


def build(runs_dir: Path, out_dir: Path) -> list[dict]:
    rows = [row for name, data in load_runs(runs_dir) for row in rows_for(name, data)]
    out_dir.mkdir(parents=True, exist_ok=True)

    with (out_dir / "results.csv").open("w", encoding="utf-8", newline="") as handle:
        # csv writes CRLF by default; artefacts are LF on every platform.
        writer = csv.DictWriter(handle, fieldnames=COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    (out_dir / "results.md").write_text(to_markdown(rows), encoding="utf-8", newline="\n")
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build report tables from run directories.")
    parser.add_argument("--runs", default="runs", help="Directory of run directories")
    parser.add_argument("--out", default="reports", help="Where to write results.csv and results.md")
    args = parser.parse_args(argv)
    rows = build(Path(args.runs), Path(args.out))
    print(f"{len(rows)} rows -> {Path(args.out) / 'results.csv'}, {Path(args.out) / 'results.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
